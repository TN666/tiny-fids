#!/usr/bin/env python3
"""Generate src/big5_table.h: CP950 (Big5) -> Unicode BMP lookup table.

Index = (lead - 0x81) * 157 + trail_index, where trail_index maps
0x40-0x7E -> 0..62 and 0xA1-0xFE -> 63..156. 0 means unmapped.
"""
import os

rows = []
for lead in range(0x81, 0xFF):
    for trail in list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF)):
        try:
            ch = bytes([lead, trail]).decode("cp950")
            cp = ord(ch) if len(ch) == 1 and ord(ch) <= 0xFFFF else 0
        except UnicodeDecodeError:
            cp = 0
        rows.append(cp)

out = os.path.join(os.path.dirname(__file__), "..", "src", "big5_table.h")
with open(out, "w") as f:
    f.write("// Generated by tools/gen_big5.py - do not edit\n#pragma once\n#include <stdint.h>\n\n")
    f.write(f"static const uint16_t BIG5_TABLE[{len(rows)}] = {{\n")
    for i in range(0, len(rows), 16):
        f.write("  " + ",".join(f"0x{c:04X}" for c in rows[i:i + 16]) + ",\n")
    f.write("};\n")
print(f"wrote {len(rows)} entries to {out}")
